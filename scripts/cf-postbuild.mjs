// Runs after `next build` (npm "postbuild"). Adds what a static export can't produce on its own:
// - out/_headers: security headers on every page and file (scripts/security-headers.mjs), long caching for hashed
//   files, and X-Robots-Tag: noindex on non-production builds
// - out/_redirects: the 301s from the retired offer pages, and the 302s from /book, /book-pe and /book-partner to
//   the Cal.com link in app/booking.json. Every source also gets a trailing-slash twin (/book/ and so on), because
//   _redirects matches the path exactly and /book/ would otherwise be a 404.
// (out/favicon.ico comes straight from app/favicon.ico, Nova's 16/32/48 px file.)
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { securityHeaders } from "./security-headers.mjs";

const out = new URL("../out/", import.meta.url);
for (const f of ["index.html", "404.html"]) {
  if (!existsSync(new URL(f, out))) throw new Error(`out/${f} is missing: did next build run with output: "export"?`);
}

// app/guides/[slug] builds a placeholder page when no guide is published (a static export needs one route). Remove it.
for (const f of ["guides/_none.html", "guides/_none.txt", "guides/_none"]) rmSync(new URL(f, out), { recursive: true, force: true });

// Same decision the pages made: a noindex build has <meta name="robots" content="noindex..."> (site.indexable).
const indexable = !/<meta name="robots" content="noindex/.test(readFileSync(new URL("index.html", out), "utf8"));

const rule = (path, headers) => [path, ...headers.map(([k, v]) => `  ${k}: ${v}`)].join("\n");
const headers = [
  "# Generated by scripts/cf-postbuild.mjs. Do not edit out/_headers by hand.",
  rule("/_next/static/*", [["Cache-Control", "public, max-age=31536000, immutable"]]),
  rule("/_img/*", [["Cache-Control", "public, max-age=86400"]]),
  // Unlisted outreach video pages (public/v/, Matt 29 Oct 2026): plain static HTML outside the Next layout, so no GTM,
  // GA4 or consent code. Clarity loads directly from /v/clarity.js without a consent wait (Matt, 29 Oct 2026; see the
  // injection step below). Never indexed or followed, and no-transform stops Cloudflare injecting anything into them.
  rule("/v/*", [["X-Robots-Tag", "noindex, nofollow"], ["Cache-Control", "public, max-age=0, must-revalidate, no-transform"]]),
  rule("/*", securityHeaders(indexable)),
].join("\n\n");
writeFileSync(new URL("_headers", out), headers + "\n");

// Every /v/ page gets Clarity (Matt, 29 Oct 2026: no consent gating on the video pages), including new pages added to
// public/v/ without the tag: add <script src="/v/clarity.js" async> before </head> where it is missing.
const vDir = new URL("v/", out);
if (existsSync(vDir)) {
  for (const f of readdirSync(vDir).filter((n) => n.endsWith(".html"))) {
    const file = new URL(f, vDir);
    let html = readFileSync(file, "utf8");
    if (!html.includes("/v/clarity.js") && html.includes("</head>")) {
      html = html.replace("</head>", '<script src="/v/clarity.js" async></script>\n</head>');
      writeFileSync(file, html);
      console.log(`cf-postbuild: added Clarity to v/${f}`);
    }
    // "Book a 20-minute call" button (Matt, 30 Oct 2026; template in scripts/v-template.html). cta.js records the
    // click in Clarity. Add it where a page has the button but not the script, and warn when a page has no button or
    // its utm_campaign does not match the page slug.
    const slug = f.replace(/\.html$/, "");
    if (html.includes('data-cta="book"') && !html.includes("/v/cta.js") && html.includes("</head>")) {
      html = html.replace("</head>", '<script src="/v/cta.js" defer></script>\n</head>');
      writeFileSync(file, html);
      console.log(`cf-postbuild: added cta.js to v/${f}`);
    }
    // Evidence pages (v-evidence-pilot, 31 Oct 2026) can use a reply-by-email CTA (data-cta="reply", report.js) in place
    // of the Book button; every http(s) link on them must carry utm_campaign=<slug>.
    if (!html.includes('data-cta="book"') && !html.includes('data-cta="reply"')) console.warn(`cf-postbuild: WARNING v/${f} has no Book or Reply button (see scripts/v-template.html)`);
    else if (html.includes('data-cta="book"') && !html.includes(`utm_campaign=${slug}"`)) console.warn(`cf-postbuild: WARNING v/${f} Book button utm_campaign does not match the slug ${slug}`);
    if (html.includes('data-cta="reply"')) {
      const bad = [...html.matchAll(/href="(https?:[^"]+)"/g)].map((m) => m[1]).filter((u) => !u.includes(`utm_campaign=${slug}&amp;utm_content=`));
      if (bad.length) console.warn(`cf-postbuild: WARNING v/${f} links without utm_campaign/utm_content: ${bad.join(" ")}`);
    }
  }
}

// Cal.com links, one per booking route. An entry that is empty falls back to the direct link, so a page never sends a
// visitor to a booking route that goes nowhere. A pe event can be added to app/booking.json later.
const booking = JSON.parse(readFileSync(fileURLToPath(new URL("../app/booking.json", import.meta.url)), "utf8"));
for (const k of ["pe"]) booking[k] ||= booking.direct;
for (const [k, v] of Object.entries(booking)) {
  if (!/^https:\/\/cal\.com\/[\w-]+\/[\w-]+$/.test(v) || /aftertheform/.test(v)) throw new Error(`app/booking.json "${k}" is not a closedlogic Cal.com link: ${v}`);
}

// Retired offer pages (the agencies, teardown, sample report and partners pages, and the stage check) go to the new
// pages with a permanent redirect. Booking routes are temporary: the Cal.com link can change.
// PE hidden (Matt, 26 Oct 2026): the old PE targets are kept below as comments, in this script and in out/_redirects, so
// they can come back. To restore, swap each live line for the commented one above it.
const redirects = [
  "# /agencies /for-pe 301",
  "/agencies / 301",
  "# /agencies/teardown /for-pe 301",
  "/agencies/teardown / 301",
  "/teardown /for-b2b-saas 301",
  "/sample-report /method 301",
  "# /partners /for-pe 301",
  "/partners / 301",
  "/tools/stage-check /method 301",
  `/book ${booking.direct} 302`,
  `# /book-pe ${booking.pe} 302`,
  "/book-pe /book 302",
  // Partner white-label offer removed (Matt, 27 Oct 2026): old /book-partner links go to the main booking route.
  "/book-partner /book 302",
];
// Trailing-slash twins: /book/ redirects exactly like /book (comments are copied as they are).
const withSlash = redirects.flatMap((r) => (r.startsWith("#") ? [r] : [r, r.replace(/^(\S+)/, "$1/")]));
writeFileSync(new URL("_redirects", out), `# Generated by scripts/cf-postbuild.mjs from app/booking.json.\n${withSlash.join("\n")}\n`);

const live = withSlash.filter((r) => !r.startsWith("#"));
const count = (code) => live.filter((r) => r.endsWith(` ${code}`)).length;
console.log(`cf-postbuild: out/_headers, out/_redirects (${count(301)} x 301, ${count(302)} x 302)\n  out/_headers (${indexable ? "indexable" : "noindex"})`);
